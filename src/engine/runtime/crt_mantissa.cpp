// Xbox 0x0016F5B2
void crt_shift_extended_right_one(CrtMantissa& value)
{
    const u32 middle = value[1];
    value[1] = middle >> 1 | value[2] << 31;
    value[2] >>= 1;
    value[0] = value[0] >> 1 | middle << 31;
}

// Xbox 0x0016F6AD
void crt_multiply_extended(CrtMantissa& value, std::span<const u8> factor)
{
    auto bytes = std::span<u8>{reinterpret_cast<u8*>(value.data()), 12};
    std::array<u8, 16> product{};
    const u16 second_exponent = read_u16(factor, 10) & 0x7FFF;
    const u16 first_exponent = read_u16(bytes, 10) & 0x7FFF;
    const u16 sign = (read_u16(factor, 10) ^ read_u16(bytes, 10)) & 0x8000;
    u16 exponent = second_exponent + first_exponent;
    i32 discarded = 0;
    if (first_exponent < 0x7FFF && second_exponent < 0x7FFF && exponent < 0xBFFE)
    {
        if (exponent < 0x3FC0)
        {
            goto zero;
        }
        if (first_exponent == 0)
        {
            ++exponent;
            if ((value[2] & 0x7FFFFFFFu) == 0 && value[1] == 0 && value[0] == 0)
            {
                const u16 zero_exponent = 0;
                std::memcpy(bytes.data() + 10, &zero_exponent, 2);
                return;
            }
        }
        if (second_exponent == 0)
        {
            ++exponent;
            if ((read_u32(factor, 8) & 0x7FFFFFFFu) == 0 && read_u32(factor, 4) == 0 && read_u32(factor, 0) == 0)
            {
                goto zero;
            }
        }
        i32 outer = 0;
        i32 remaining = 5;
        do
        {
            if (0 < remaining)
            {
                i32 left = outer * 2;
                i32 right = 8;
                // Offset +12 is the original inner-loop counter stack slot.
                std::memcpy(product.data() + 12, &remaining, 4);
                do
                {
                    const u32 term = u32(read_u16(factor, right)) * u32(read_u16(bytes, left));
                    u32 sum;
                    const u32 carry = crt_add_word(read_u32(product, outer * 2), term, sum);
                    std::memcpy(product.data() + outer * 2, &sum, 4);
                    if (carry != 0)
                    {
                        const u16 incremented = read_u16(product, outer * 2 + 4) + 1;
                        std::memcpy(product.data() + outer * 2 + 4, &incremented, 2);
                    }
                    left += 2;
                    right -= 2;
                    const u32 count = read_u32(product, 12) - 1;
                    std::memcpy(product.data() + 12, &count, 4);
                }
                while (read_u32(product, 12) != 0);
            }
            ++outer;
            --remaining;
        }
        while (0 < remaining);
        exponent += 0xC002;
        if (static_cast<i16>(exponent) > 0)
        {
            do
            {
                if ((product[11] & 0x80) != 0)
                {
                    break;
                }
                CrtMantissa shifted;
                std::memcpy(shifted.data(), product.data(), 12);
                crt_shift_mantissa_left(shifted);
                std::memcpy(product.data(), shifted.data(), 12);
                --exponent;
            }
            while (static_cast<i16>(exponent) > 0);
        }
        if (static_cast<i16>(exponent) < 1)
        {
            --exponent;
            if (static_cast<i16>(exponent) < 0)
            {
                u32 shifts = static_cast<u16>(0u - exponent);
                exponent = 0;
                do
                {
                    if ((product[0] & 1) != 0)
                    {
                        ++discarded;
                    }
                    CrtMantissa shifted;
                    std::memcpy(shifted.data(), product.data(), 12);
                    crt_shift_extended_right_one(shifted);
                    std::memcpy(product.data(), shifted.data(), 12);
                    --shifts;
                }
                while (shifts != 0);
                if (discarded != 0)
                {
                    product[0] |= 1;
                }
            }
        }
        u32 low = read_u32(product, 2);
        u32 middle = read_u32(product, 6);
        u16 high = read_u16(product, 10);
        if (read_u16(product, 0) > 0x8000 || (read_u32(product, 0) & 0x1FFFF) == 0x18000)
        {
            if (low == 0xFFFFFFFFu)
            {
                low = 0;
                if (middle == 0xFFFFFFFFu)
                {
                    middle = 0;
                    if (high == 0xFFFF)
                    {
                        ++exponent;
                        high = 0x8000;
                    }
                    else
                    {
                        ++high;
                    }
                }
                else
                {
                    ++middle;
                }
            }
            else
            {
                ++low;
            }
        }
        if (exponent > 0x7FFE)
        {
            goto infinity;
        }
        const u16 bottom = static_cast<u16>(low);
        const u32 next = low >> 16 | middle << 16;
        const u32 top = middle >> 16 | u32(high) << 16;
        const u16 signed_exponent = exponent | sign;
        std::memcpy(bytes.data(), &bottom, 2);
        std::memcpy(bytes.data() + 2, &next, 4);
        std::memcpy(bytes.data() + 6, &top, 4);
        std::memcpy(bytes.data() + 10, &signed_exponent, 2);
        return;
    }
infinity:
    value[0] = 0;
    value[1] = 0;
    value[2] = (0u - u32(sign != 0) & 0x80000000u) + 0x7FFF8000u;
    return;
zero:
    value[2] = 0;
    value[1] = 0;
    value[0] = 0;
}

// Xbox 0x0016F8CF
void crt_scale_extended_decimal(CrtMantissa& value, i32 exponent, i32 preserve_tail)
{
    std::span<const u8> table = positive_decimal_scale;
    if (exponent != 0)
    {
        if (exponent < 0)
        {
            exponent = static_cast<i32>(0u - static_cast<u32>(exponent));
            table = negative_decimal_scale;
        }
        if (preserve_tail == 0)
        {
            value[0] &= 0xFFFF0000u;
        }
        i32 offset = 0;
        while (exponent != 0)
        {
            const u32 index = static_cast<u32>(exponent) & 7;
            exponent >>= 3;
            offset += 0x54;
            if (index != 0)
            {
                auto factor = table.subspan(offset + index * 12, 12);
                std::array<u8, 12> adjusted;
                if (read_u16(factor, 0) > 0x7FFF)
                {
                    std::memcpy(adjusted.data(), factor.data(), 12);
                    const u32 mantissa = read_u32(adjusted, 2) - 1;
                    std::memcpy(adjusted.data() + 2, &mantissa, 4);
                    factor = adjusted;
                }
                crt_multiply_extended(value, factor);
            }
        }
    }
}

// Xbox 0x0016F505
u32 crt_add_word(u32 first, u32 second, u32& output)
{
    const u32 sum = first + second;
    u32 carry = 0;
    if (sum < first || sum < second)
    {
        carry = 1;
    }
    output = sum;
    return carry;
}

// Xbox 0x0016F526
void crt_add_mantissa(CrtMantissa& output, const CrtMantissa& value)
{
    if (crt_add_word(output[0], value[0], output[0]) != 0)
    {
        if (crt_add_word(output[1], 1, output[1]) != 0)
        {
            ++output[2];
        }
    }
    if (crt_add_word(output[1], value[1], output[1]) != 0)
    {
        ++output[2];
    }
    crt_add_word(output[2], value[2], output[2]);
}

// Xbox 0x0016F584
void crt_shift_mantissa_left(CrtMantissa& value)
{
    const u32 low = value[0];
    const u32 middle = value[1];
    value[0] = low * 2;
    value[1] = middle * 2 | low >> 31;
    value[2] = value[2] << 1 | middle >> 31;
}

// Xbox 0x0016E44C
u32 crt_mantissa_tail_zero(const CrtMantissa& value, i32 bit)
{
    i32 index = bit / 32;
    u32 tail = value[index] & ~(0xFFFFFFFFu << ((31 - bit % 32) & 31));
    while (true)
    {
        if (tail != 0)
        {
            return 0;
        }
        ++index;
        if (2 < index)
        {
            break;
        }
        tail = value[index];
    }
    return 1;
}

// Xbox 0x0016E47E
u32 crt_increment_mantissa(CrtMantissa& value, i32 bit)
{
    i32 index = bit / 32;
    u32 carry = crt_add_word(value[index], 1u << ((31 - bit % 32) & 31), value[index]);
    --index;
    if (-1 < index)
    {
        do
        {
            if (carry == 0)
            {
                return carry;
            }
            carry = crt_add_word(value[index], 1, value[index]);
            --index;
        }
        while (-1 < index);
    }
    return carry;
}

// Xbox 0x0016E4CB
u32 crt_round_mantissa(CrtMantissa& value, i32 bit)
{
    u32 carry = 0;
    i32 index = bit / 32;
    const u32 shift = (31 - bit % 32) & 31;
    if ((value[index] & (1u << shift)) != 0 && crt_mantissa_tail_zero(value, bit) == 0)
    {
        carry = crt_increment_mantissa(value, bit - 1);
    }
    value[index] &= 0xFFFFFFFFu << shift;
    ++index;
    if (index < 3)
    {
        i32 remaining = 3 - index;
        do
        {
            value[index++] = 0;
            --remaining;
        }
        while (remaining != 0);
    }
    return carry;
}

// Xbox 0x0016E53D
void crt_copy_mantissa(CrtMantissa& output, const CrtMantissa& value)
{
    i32 index = 0;
    i32 remaining = 3;
    do
    {
        output[index] = value[index];
        ++index;
        --remaining;
    }
    while (remaining != 0);
}

// Xbox 0x0016E558
u32 crt_mantissa_zero(const CrtMantissa& value)
{
    i32 index = 0;
    do
    {
        if (value[index] != 0)
        {
            return 0;
        }
        ++index;
    }
    while (index < 3);
    return 1;
}

// Xbox 0x0016E571
