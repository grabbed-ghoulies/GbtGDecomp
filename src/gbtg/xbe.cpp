size_t find_pat(const std::vector<u8>& hay, const u8* needle, size_t nlen, size_t from = 0)
{
    if (nlen == 0 || hay.size() < nlen)
    {
        return size_t(-1);
    }
    for (size_t i = from; i + nlen <= hay.size(); ++i)
    {
        if (std::memcmp(hay.data() + i, needle, nlen) == 0)
        {
            return i;
        }
    }
    return size_t(-1);
}

size_t va_to_off(const std::vector<u8>& bytes, u32 va)
{
    if (bytes.size() < 0x178)
    {
        throw Error("not an XBE");
    }
    const u32 base = read_u32(bytes, 0x104);
    const u32 nsect = read_u32(bytes, 0x11C);
    const u32 sect_addr = read_u32(bytes, 0x120);
    if (sect_addr < base)
    {
        throw Error("bad section table");
    }
    const size_t soff = sect_addr - base;
    for (u32 i = 0; i < nsect && i < 64; ++i)
    {
        const size_t rec = soff + i * 56;
        const u32 sva = read_u32(bytes, rec + 4);
        const u32 vsz = read_u32(bytes, rec + 8);
        const u32 raw = read_u32(bytes, rec + 12);
        const u32 rsz = read_u32(bytes, rec + 16);
        if (va >= sva && va < sva + vsz)
        {
            const u32 rel = va - sva;
            if (rel < rsz && raw + rel < bytes.size())
            {
                return raw + rel;
            }
            throw Error("VA not file-backed");
        }
    }
    throw Error("VA not in any section");
}

